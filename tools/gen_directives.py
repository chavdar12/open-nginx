#!/usr/bin/env python3
"""Generate src/main/resources/nginx/{directives,variables,parameters}.tsv from a checkout of
https://github.com/nginx/nginx.org (BSD-2-Clause).

usage: python3 tools/gen_directives.py <path-to-nginx.org-checkout>
"""
import html, math, pathlib, re, sys

root = pathlib.Path(sys.argv[1]) / "xml/en/docs"
res = pathlib.Path(__file__).parent.parent / "src/main/resources/nginx"
HEADER = ("# Generated by tools/gen_directives.py from https://github.com/nginx/nginx.org\n"
          "# Copyright (C) 2002-2021 Igor Sysoev, (C) 2011-2026 Nginx, Inc. BSD-2-Clause.\n")


def text(s):
    s = re.sub(r'<link[^>]*\bid="([^"]+)"[^>]*/>', r"\1", s)  # self-closing links carry their text in id
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", s)).split())


# nginx.org markup -> the HTML the quick-doc popup renders; everything else is stripped and escaped
TAGS = {"literal": "code", "var": "code", "header": "code", "path": "code", "value": "i", "emphasis": "i", "example": "pre"}


def to_html(s):
    """One line of HTML (a TSV cell): line breaks survive only inside <pre>, as <br>."""
    s = re.sub(r'<link[^>]*\bid="([^"]+)"[^>]*/>', r"\1", s)
    s = re.sub(r"<example>\s*\n(.*?)\n?\s*</example>", r"<example>\1</example>", s, flags=re.S)
    out = []
    for part in re.split(r"(<example>.*?</example>)", s, flags=re.S):
        pre = part.startswith("<example>")
        part = re.sub(r"</?(\w[\w-]*)[^>]*>", lambda m: "\x01%s%s\x02" % ("/" if m.group(0)[1] == "/" else "", TAGS[m.group(1)])
                      if m.group(1) in TAGS else "", part)
        part = html.escape(html.unescape(part), quote=False)
        part = part.strip("\n").replace("\n", "<br>") if pre else " ".join(part.split())
        out.append(part.replace("\x01", "<").replace("\x02", ">"))
    return " ".join(p for p in out if p)


def ctx(c):
    c = text(c)
    return "if" if c.startswith("if") else c  # "if in location" -> the if block


def tokens(s):
    """Split a syntax line into '[', ']', '|', '...' and words; brackets/quotes glued to a word stay in it."""
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c.isspace():
            i += 1
        elif s.startswith("...", i):
            out.append("..."); i += 3
        elif c in "[]|":
            out.append(c); i += 1
        else:
            j, depth = i, 0
            while j < len(s) and not (s[j].isspace() or (s[j] == "]" and depth == 0)):
                if s[j] == "'":
                    j = s.find("'", j + 1) if s.find("'", j + 1) > 0 else len(s) - 1
                depth += {"[": 1, "]": -1}.get(s[j], 0)
                j += 1
            w = s[i:j]
            if w.endswith("...") and len(w) > 3:
                out += [w[:-3], "..."]
            else:
                out.append(w)
            i = j
    return out


def bounds(toks):
    """(min, max) argument count of a syntax line; max may be math.inf."""
    pos = 0

    def seq():  # alt ('|' alt)*
        nonlocal pos
        lo, hi = alt()
        while pos < len(toks) and toks[pos] == "|":
            pos += 1
            a, b = alt()
            lo, hi = min(lo, a), max(hi, b)
        return lo, hi

    def alt():
        nonlocal pos
        lo = hi = 0
        while pos < len(toks) and toks[pos] not in "|]":
            if toks[pos] == "[":
                pos += 1
                _, b = seq()
                assert toks[pos] == "]", toks
                pos += 1
                a = 0
            elif toks[pos] == "...":
                pos += 1
                hi = math.inf
                continue
            elif toks[pos] == "parameters":  # "[parameters]" stands for any number of key=value options
                pos += 1
                a, b = 1, math.inf
            else:
                pos += 1
                a = b = 1
            lo, hi = lo + a, hi + b
        return lo, hi

    r = seq()
    assert pos == len(toks), toks
    return r


data = {}  # name -> dict
for f in sorted(root.rglob("*.xml")):
    rel = f.relative_to(root).with_suffix(".html").as_posix()
    for name, body in re.findall(r'<directive name="([^"]+)">(.*?)</directive>', f.read_text("utf-8"), re.S):
        d = data.setdefault(name, {"ctx": set(), "syntax": [], "raw": [], "html": [], "url": None})
        d["ctx"].update(ctx(c) for c in re.findall(r"<context>(.*?)</context>", body, re.S))
        raws = re.findall(r"<syntax[^>]*?(?:/>|>(.*?)</syntax>)", body, re.S)
        if d["url"] is None:  # first module wins for docs; arg rules merge across modules
            d["url"] = f"https://nginx.org/en/docs/{rel}#{name}"
            m = re.search(r"<default>(.*?)</default>", body, re.S)
            d["default"] = text(m.group(1)) if m else ""
            m = re.search(r"<para>(.*?)</para>", body, re.S)
            d["doc"] = to_html(m.group(1)) if m else ""
        d["raw"] += raws
        # one HTML line per syntax form; block directives get their braces
        d["html"] += [to_html(r) + (" { … }" if "yes" in attrs else "")
                      for attrs, r in re.findall(r"<syntax([^>]*?)(?:/>|>(.*?)</syntax>)", body, re.S) if r.strip()]
        d["syntax"] += [text(r) for r in raws]

FREE_ARGS = {"if"}  # condition is split into several nginx tokens: "($a", "=", "b)"
# real directives missing from the docs
UNDOCUMENTED = {"post_action": {"ctx": {"http", "server", "location", "if"}, "syntax": ["uri | off"], "raw": [], "html": ["<i>uri</i> | <code>off</code>"],
                                "url": "https://github.com/nginx/nginx/blob/master/src/http/ngx_http_core_module.c",
                                "default": "off", "doc": "Undocumented: runs a subrequest to uri after the request completes."}}
data.update(UNDOCUMENTED)
lit = re.compile(r"\s*<literal>([^<]+)</literal>\s*")
rows, failed = [], []
for name in sorted(data):
    d = data[name]
    try:
        if name in FREE_ARGS:
            raise AssertionError
        bs = [bounds(tokens(s)) for s in d["syntax"]] or [(0, 0)]
        lo, hi = min(b[0] for b in bs), max(b[1] for b in bs)
    except (AssertionError, IndexError):
        failed.append(name)
        lo, hi = 0, math.inf  # unknown syntax: don't check
    # a pure "a | b | c" literal choice in every syntax variant -> allowed values
    alts = [r.split("|") for r in d["raw"]]
    values = ""
    if alts and all(all(lit.fullmatch(a) for a in alt) for alt in alts):
        values = ",".join(dict.fromkeys(lit.fullmatch(a).group(1) for alt in alts for a in alt))
    rows.append([name, ",".join(sorted(d["ctx"])), str(lo), "" if hi == math.inf else str(hi), values,
                 d["url"], d["default"], "<br>".join(dict.fromkeys(d["html"])), d["doc"]])

assert len(rows) > 500, f"only {len(rows)} directives found, wrong path?"
assert len(failed) < 10, f"syntax parse failed for {failed}"
res.mkdir(parents=True, exist_ok=True)
with (res / "directives.tsv").open("w") as w:
    w.write(HEADER + "# name\tcontexts\tmin args\tmax args (empty = unlimited)\tallowed values\turl\tdefault\tsyntax (HTML, one form per <br>)\tdoc (HTML)\n")
    for r in rows:
        w.write("\t".join(r) + "\n")

variables = {}
for f in sorted(root.rglob("*.xml")):
    rel = f.relative_to(root).with_suffix(".html").as_posix()
    for vid, var, desc in re.findall(r'<tag-name\s+id="(var_[^"]+)">\s*<var>(\$[^<]+)</var>.*?</tag-name>\s*<tag-desc>(.*?)(?:<para>|</tag-desc>)',
                                     f.read_text("utf-8"), re.S):
        variables.setdefault(var[1:], (f"https://nginx.org/en/docs/{rel}#{vid}", to_html(desc)))
with (res / "variables.tsv").open("w") as w:
    w.write(HEADER + "# name (a trailing _ is a prefix, e.g. arg_ for $arg_name)\turl\tdoc (HTML)\n")
    for v in sorted(variables):
        w.write(f"{v}\t{variables[v][0]}\t{variables[v][1]}\n")



def cut(t, limit=600):
    """Shorten to whole sentences, never inside an HTML element."""
    if len(t) <= limit:
        return t
    end = limit
    while (end := t.rfind(". ", 0, end)) > 0:
        head = t[:end + 1]
        if all(head.count(f"<{x}>") == head.count(f"</{x}>") for x in ("code", "i", "pre")):
            return head
    return re.sub(r"<[^>]+>", "", t)[:limit] + "…"


# parameter docs: "<tag-name><literal>weight</literal>=...</tag-name><tag-desc>..." lists, or the
# paragraph sentence that introduces "<literal>levels</literal>" for name= parameters in the syntax
params = {}  # (directive, parameter) -> doc
for f in sorted(root.rglob("*.xml")):
    for name, body in re.findall(r'<directive name="([^"]+)">(.*?)</directive>', f.read_text("utf-8"), re.S):
        for tag, desc in re.findall(r"<tag-name[^>]*>\s*(.*?)</tag-name>\s*<tag-desc>(.*?)</tag-desc>", body, re.S):
            m = re.match(r"<literal>([\w-]+)</literal>", tag)
            if m:
                params.setdefault((name, m.group(1)), cut(to_html(desc)))
        syntax = " ".join(re.findall(r"<syntax[^>]*>(.*?)</syntax>", body, re.S))
        keyed = set(re.findall(r"<literal>(\w+)</literal>=", syntax))
        for p in dict.fromkeys(re.findall(r"<literal>(\w+)</literal>", syntax)):
            if (name, p) in params:
                continue
            for para in re.findall(r"<para>(.*?)</para>", body, re.S):
                if f"<literal>{p}</literal>" in para:
                    t = to_html(para.replace(f"<literal>{p}</literal>", f"\x00<literal>{p}</literal>", 1))
                    i = t.find("\x00")
                    start = t.rfind(". ", 0, i) + 2 if t.rfind(". ", 0, i) >= 0 else 0
                    sentence = t[start:t.find(". ", i) + 1 or len(t)]
                    # bare flags (ssl, default_server) only when the docs call them a parameter, so on/off get nothing
                    if p in keyed or "parameter" in sentence:
                        params[(name, p)] = cut(t[start:].replace("\x00", ""))
                    break
with (res / "parameters.tsv").open("w") as w:
    w.write(HEADER + "# directive\tparameter\tdoc (HTML)\n")
    for (d, p) in sorted(params):
        w.write(f"{d}\t{p}\t{params[(d, p)]}\n")

# obsolete directives: the docs keep them with a "This directive was made obsolete in version ..." paragraph
obsolete = {}
for f in sorted(root.rglob("*.xml")):
    for name, body in re.findall(r'<directive name="([^"]+)">(.*?)</directive>', f.read_text("utf-8"), re.S):
        for para in re.findall(r"<para>(.*?)</para>", body, re.S):
            if re.search(r"directive (is|was made) obsolete", para):
                obsolete.setdefault(name, cut(text(para), 300))
with (res / "obsolete.tsv").open("w") as w:
    w.write(HEADER + "# directive\tnote from the docs\n")
    for n in sorted(obsolete):
        w.write(f"{n}\t{obsolete[n]}\n")

print(f"{len(obsolete)} obsolete, {len(params)} parameters, ", end="")
print(f"{len(rows)} directives ({len(failed)} with unparsed syntax: {failed}), {len(variables)} variables -> {res}")
