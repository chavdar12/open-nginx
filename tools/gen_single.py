#!/usr/bin/env python3
"""Generate src/main/resources/nginx/single.tsv: directives nginx rejects with "is duplicate" when repeated in one block,
taken from a checkout of https://github.com/nginx/nginx (BSD-2-Clause).

A directive counts when its handler returns "is duplicate" under conditions that only look at what is already set,
not at the arguments (limit_req per zone, `mirror off` mixed with `mirror /x`, proxy_redirect after `off`).

usage: python3 tools/gen_single.py <path-to-nginx-checkout>
"""
import pathlib, re, sys

src = pathlib.Path(sys.argv[1]) / "src"
out = pathlib.Path(__file__).parent.parent / "src/main/resources/nginx/single.tsv"
FUNC = re.compile(r"\n(?:static\s+)?char\s*\*\s*\n(\w+)\([^)]*\)\s*\n\{(.*?)\n\}", re.S)
COMMAND = re.compile(r'\{\s*ngx_string\("(\w+)"\),[^,]+,\s*(\w+),')
# an enclosing condition that depends on the arguments or on an earlier "off"
ARG_DEPENDENT = re.compile(r"value\[|cf->args|== NULL|== 0\b")


def always_duplicate(body):
    """True if some `return "is duplicate"` sits only under ifs that test the existing configuration."""
    lines = body.split("\n")
    for i, line in enumerate(lines):
        if '"is duplicate"' not in line:
            continue
        indent, ok = len(line) - len(line.lstrip()), True
        for prev in reversed(lines[:i]):
            stripped = prev.lstrip()
            if not stripped or len(prev) - len(stripped) >= indent:
                continue
            indent = len(prev) - len(stripped)
            if stripped.startswith(("for ", "while ", "} else", "else", "switch ")) or \
                    stripped.startswith("if ") and ARG_DEPENDENT.search(stripped):
                ok = False
                break
        if ok:
            return True
    return False


files = sorted(src.rglob("*.c"))
handlers = {m.group(1) for f in files for m in FUNC.finditer(f.read_text(errors="replace")) if always_duplicate(m.group(2))}
commands = [m.groups() for f in files for m in COMMAND.finditer(f.read_text(errors="replace"))]
# the same name in http and stream may differ: http's `return` repeats, stream's does not
names = sorted({n for n, _ in commands} - {n for n, h in commands if h not in handlers})
assert {"root", "proxy_pass", "try_files", "worker_processes"} <= set(names), "parser missed the core directives"
assert not {"limit_req", "mirror", "proxy_redirect", "add_header", "listen", "return", "ssl_protocols"} & set(names), "argument-dependent handler slipped in"
out.write_text("# Generated by tools/gen_single.py from https://github.com/nginx/nginx\n"
               "# Copyright (C) 2002-2021 Igor Sysoev, (C) 2011-2026 Nginx, Inc. BSD-2-Clause.\n"
               "# directives that may appear only once per block\n" + "".join(n + "\n" for n in names))
print(len(names), "directives")
